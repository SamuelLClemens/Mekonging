// ---- IS THERE WATER IN THE WAY? ---------------------------------------------
// The emergency screens measure every hospital by straight-line distance and turn it into a
// walking or road time. That is honest on the mainland and nonsense on an island: from Koh Mak
// the app used to offer "Koh Kood Hospital — 30 min to 1 h by road", a hospital on another
// island with no road to it, and it had no way to know better, because the basemap is simplified
// far below the size of the islands people actually stay on.
//
// This module answers the one question those screens were missing — are these two points on the
// same landmass? — from js/data/islands.geo.js: the outline of every island in the four
// countries that has a settlement, a place to stay, a clinic or a place the app lists on it
// (generated by scripts/build_islands.py from OpenStreetMap). Islands road-bridged to the
// mainland are not in that file, so Phuket reads as mainland; islands bridged to each other
// (Koh Lanta Yai and Noi) share a road group and read as one.
//
// Loaded on demand like the hospital layer, and precached, because the question matters most
// exactly where there is no signal. Until it has loaded, every answer here is `null` — "not
// known yet" — and callers must fall back to their old wording rather than guess.

let ISLANDS = null;
let INFLIGHT = null;

export function islandsLoaded() { return !!ISLANDS; }

export function loadIslands() {
  if (ISLANDS) return Promise.resolve(ISLANDS);
  if (INFLIGHT) return INFLIGHT;
  INFLIGHT = import('./islands.geo.js')
    .then((m) => { ISLANDS = decode(m.ISLAND_ROWS || []); return ISLANDS; })
    .catch((err) => { INFLIGHT = null; throw err; });
  return INFLIGHT;
}

// Row: [osmKey, name, localName|0, cc, roadGroup, toleranceM, [minLat, minLng, maxLat, maxLng], rings]
// with each ring a flat, delta-encoded run of 1e-4 degree integers.
function decode(rows) {
  return rows.map(([key, name, local, cc, group, tol, bb, rings]) => ({
    key, name, local: local || name, cc, group, tol,
    s: bb[0], w: bb[1], n: bb[2], e: bb[3],
    rings: rings.map((flat) => {
      const ring = [];
      let lat = 0, lng = 0;
      for (let i = 0; i + 1 < flat.length; i += 2) {
        lat += flat[i]; lng += flat[i + 1];
        ring.push([lat / 1e4, lng / 1e4]);
      }
      return ring;
    }),
  }));
}

function inRing(lat, lng, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [yi, xi] = ring[i], [yj, xj] = ring[j];
    if ((yi > lat) !== (yj > lat) && lng < ((xj - xi) * (lat - yi)) / ((yj - yi) || 1e-12) + xi) inside = !inside;
  }
  return inside;
}

// Metres from a point to the nearest edge of a ring, on a local flat projection — accurate to a
// few per cent at these latitudes over the size of one island, which is all this needs.
function metresToRing(lat, lng, ring) {
  const kx = 111320 * Math.cos((lat * Math.PI) / 180), ky = 110540;
  const px = lng * kx, py = lat * ky;
  let best = Infinity;
  for (let i = 0; i + 1 < ring.length; i += 1) {
    const ax = ring[i][1] * kx, ay = ring[i][0] * ky, bx = ring[i + 1][1] * kx, by = ring[i + 1][0] * ky;
    const dx = bx - ax, dy = by - ay;
    const t = dx || dy ? Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy))) : 0;
    const d = Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
    if (d < best) best = d;
  }
  return best;
}

// The outlines are simplified, so a beach bar on the tideline or a boat tied up at the pier can
// fall a few tens of metres outside one. A point that close to an island's coast is treated as on
// it. The margin grows with the island's own simplification tolerance and never drops below 60 m;
// it stays well short of the Mekong's narrowest channels, where a river island sits a few hundred
// metres from the bank.
const coastMargin = (x) => Math.max(60, 2 * x.tol);

const _memo = new Map();

// The island a point is on, or null for the mainland (or the open sea). Returns null too while the
// outlines have not loaded, so check islandsLoaded() before reading "null" as "mainland".
export function islandAt(p) {
  if (!ISLANDS || !p || typeof p.lat !== 'number' || typeof p.lng !== 'number') return null;
  const key = `${p.lat.toFixed(5)},${p.lng.toFixed(5)}`;
  if (_memo.has(key)) return _memo.get(key);
  let hit = null, near = null, nearM = Infinity;
  for (const x of ISLANDS) {
    const m = coastMargin(x), pad = m / 100000;
    if (p.lat < x.s - pad || p.lat > x.n + pad || p.lng < x.w - pad || p.lng > x.e + pad) continue;
    if (x.rings.some((r) => inRing(p.lat, p.lng, r))) { hit = x; break; }
    const d = Math.min(...x.rings.map((r) => metresToRing(p.lat, p.lng, r)));
    if (d <= m && d < nearM) { near = x; nearM = d; }
  }
  const out = hit || near;
  if (_memo.size > 2000) _memo.clear();
  _memo.set(key, out);
  return out;
}

function landOf(p) {
  const x = islandAt(p);
  if (!x) return 'mainland';
  return x.group ? `g${x.group}` : x.key;
}

// true: same landmass, a road or a walk can connect them. false: water in between — a boat, or a
// flight, is part of the journey. null: the outlines are not loaded yet, so nobody knows.
export function sameLand(a, b) {
  if (!ISLANDS || !a || !b) return null;
  return landOf(a) === landOf(b);
}

// Every other island that shares a road with this one (a bridged pair), including itself.
export function roadGroupOf(island) {
  if (!ISLANDS || !island) return [];
  return island.group ? ISLANDS.filter((x) => x.group === island.group) : [island];
}
