// authorities before it was written (see research method note at the foot of this file) —
// the same bar the app's own maintainer set for this file: "all info five sources that
// agree... be sure it all checks out for users to live or die on this information." Where
// sources genuinely disagree (there are several real, current splits — infant CPR hand
