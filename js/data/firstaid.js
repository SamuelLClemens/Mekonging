// picking a side silently, and the wording used is the one every side accepts as safe.
//
// THE CONTRACT — same as js/data/medical.js and js/data/island-care.js:
//   * No telephone numbers except a country's own national emergency number, which this file
//     does not carry at all — it is read from country data (js/data/regions.<cc>.js) by the
//     screen itself, exactly as the SOS and hospital screens already do, so there is only
//     ever one place in the app that can get that number wrong.
//   * Every claim traces to `srcs` — indices into FIRSTAID_SOURCES below. Nothing here is
//     a diagnosis or a treatment decision, and nothing replaces calling for help.
//   * Regional/product-specific numbers (drug doses, timings) are given as the range every
//     agreeing source supports, not a single invented average.
//
// SHAPE. One flat list of topics, each tagged with the section it belongs under and the
// traveller views it is especially relevant to. Nothing is ever hidden by view — a solo
// traveller still gets the baby-choking steps if they look, and a parent still gets the
// snakebite steps — `views` only decides what opens first and what is badged "for you".
// js/screens/firstaid.js does all the view/ordering logic; this file is pure content.

